def backup_configs(configs: list[ModelConfig], user_id: int) -> Path:
    directory = Path(__file__).resolve().parent / "data" / "model_config_backups"
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"user_{user_id}_{datetime.now():%Y%m%d_%H%M%S}.json"
    payload = [
        {
            "id": config.id,
            "name": config.name,
            "agent_type": config.agent_type,
            "system_prompt": config.system_prompt,
            "params_json": config.params_json,
            "legacy_skills": config.skills,
        }
        for config in configs
    ]
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def seed(user_id: int) -> Path:
    init_db()
    db = SessionLocal()
    try:
        configs = db.scalars(
            select(ModelConfig).where(
                ModelConfig.user_id == user_id,
                ModelConfig.agent_type.in_(SYSTEM_PROMPTS),
                ModelConfig.is_default == True,  # noqa: E712
            )
        ).all()
        config_by_agent = {config.agent_type: config for config in configs}
        missing = set(SYSTEM_PROMPTS) - set(config_by_agent)
        if missing:
            raise RuntimeError(f"用户 {user_id} 缺少默认 Agent 配置：{'、'.join(sorted(missing))}")

        backup_path = backup_configs(configs, user_id)
        existing = {
            skill.name: skill
            for skill in db.scalars(
                select(Skill).where(Skill.user_id == user_id, Skill.name.in_(SKILLS))
            ).all()
        }
        for name, (description, content) in SKILLS.items():
            skill = existing.get(name)
            if skill is None:
                skill = Skill(
                    user_id=user_id,
                    name=name,
                    description=description,
                    content=content,
                    source_type="seeded",
                )
                db.add(skill)
                existing[name] = skill
            else:
                skill.description = description
                skill.content = content
                skill.source_type = "seeded"
        db.flush()

        for agent_type, prompt in SYSTEM_PROMPTS.items():
            config = config_by_agent[agent_type]
            config.system_prompt = prompt
            params = json.loads(config.params_json or "{}")
            if not isinstance(params, dict):
                params = {}
            for name, value in PARAMS[agent_type].items():
                entry = dict(params.get(name) or {})
                entry["enabled"] = True
                entry["value"] = value
                params[name] = entry
            config.params_json = json.dumps(params, ensure_ascii=False)
            update_config_skills(
                db, config, [existing[name].id for name in ATTACHMENTS[agent_type]]
            )
        db.commit()
        return backup_path
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--user-id", type=int, required=True)
    args = parser.parse_args()
    result = seed(args.user_id)
    print(f"已更新用户 {args.user_id} 的模型配置与 Skills；备份：{result}")
